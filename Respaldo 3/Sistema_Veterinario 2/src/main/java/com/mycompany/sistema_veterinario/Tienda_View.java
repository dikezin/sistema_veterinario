    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
int fila = TablaTienda.getSelectedRow();

    if (fila == -1) {
        JOptionPane.showMessageDialog(this, "Seleccione un producto");
        return;
    }

    // 1. Obtener datos de la fila seleccionada
    String id = TablaTienda.getValueAt(fila, 0).toString();
    String nombre = TablaTienda.getValueAt(fila, 1).toString();
    int stockDisponible = Integer.parseInt(TablaTienda.getValueAt(fila, 4).toString());

    // 2. Pedir cantidad para el carrito
    String input = JOptionPane.showInputDialog(this, 
        "Producto: " + nombre + "\nStock disponible: " + stockDisponible + "\n¿Cuántos desea agregar?");
    
    if (input == null || input.isEmpty()) return;

    try {
        int cantidadAAgregar = Integer.parseInt(input);

        // 3. Validaciones rápidas
        if (cantidadAAgregar <= 0) {
            JOptionPane.showMessageDialog(this, "Debe agregar al menos 1 unidad");
            return;
        }

        if (cantidadAAgregar > stockDisponible) {
            JOptionPane.showMessageDialog(this, "No hay suficiente stock. Solo quedan " + stockDisponible);
            return;
        }

        // 4. Buscar el producto y agregarlo la cantidad de veces necesaria
        for (Productos p : Productos_Manager.listarProductos()) {
            if (p.getId().equals(id)) {
                // Agregamos el producto al carrito según la cantidad pedida
                for (int i = 0; i < cantidadAAgregar; i++) {
                    carrito.agregarProducto(p);
                }
                JOptionPane.showMessageDialog(this, cantidadAAgregar + " unidades de '" + nombre + "' agregadas al carrito");
                return;
            }
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Error: Ingrese un número entero válido");
    }       // TODO add your handling code here:
    }//GEN-LAST:event_jButton1ActionPerformed

