private void generarFacturaTXT(String producto, int cant, double precio, double sub, double iva, double total) {
    try (java.io.PrintWriter writer = new java.io.PrintWriter(new java.io.FileWriter("factura_" + System.currentTimeMillis() + ".txt"))) {
        writer.println("========================================");
        writer.println("           VeterinariaDesk             ");
        writer.println("========================================");
        writer.println("Fecha: " + new java.util.Date());
        writer.println("----------------------------------------");
        writer.println("Producto: " + producto);
        writer.println("Cantidad: " + cant);
        writer.println("Precio Unit.: $" + precio);
        writer.println("----------------------------------------");
        writer.println("Subtotal: $" + String.format("%.2f", sub));
        writer.println("IVA (15%): $" + String.format("%.2f", iva));
        writer.println("TOTAL A PAGAR: $" + String.format("%.2f", total));
        writer.println("----------------------------------------");
        writer.println("   ¡Gracias por confiar en nosotros!    ");
        writer.println("========================================");
    } catch (java.io.IOException e) {
        System.out.println("Error al crear la factura: " + e.getMessage());
    }
}
    private void btComprarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btComprarActionPerformed
        // TODO add your handling code here:
      int fila = TablaTienda.getSelectedRow();

    if (fila == -1) {
        JOptionPane.showMessageDialog(this, "Seleccione un producto");
        return;
    }

    String id = TablaTienda.getValueAt(fila, 0).toString();
    String nombre = TablaTienda.getValueAt(fila, 1).toString();
    double precioUnitario = Double.parseDouble(TablaTienda.getValueAt(fila, 3).toString());
    int stockDisponible = Integer.parseInt(TablaTienda.getValueAt(fila, 4).toString());

    String input = JOptionPane.showInputDialog(this, "¿Cantidad de " + nombre + " a comprar?");
    if (input == null || input.isEmpty()) return;

    try {
        int cantidad = Integer.parseInt(input);
        if (cantidad <= 0 || cantidad > stockDisponible) {
            JOptionPane.showMessageDialog(this, "Cantidad no válida o stock insuficiente");
            return;
        }

        // Cálculos financieros
        double subtotal = precioUnitario * cantidad;
        double iva = subtotal * 0.15; // Ajusta al 15% o según tu país
        double total = subtotal + iva;

        // 1. Procesar la compra en el sistema
        for(int i = 0; i < cantidad; i++) {
            Productos_Manager.comprarProducto(id);
        }

        // 2. GENERAR FACTURA TXT
        generarFacturaTXT(nombre, cantidad, precioUnitario, subtotal, iva, total);

        JOptionPane.showMessageDialog(this, "¡Compra exitosa! Factura generada como 'factura_" + id + ".txt'");
        cargarProductosEnTabla();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error al procesar la compra");
    }

    }//GEN-LAST:event_btComprarActionPerformed

